#!/usr/bin/env node
/**
 * Pulls the latest WooNuxt release into this storefront using a 3-way merge.
 *
 *   base   = upstream tag matching the version in woonuxt_base/package.json
 *   theirs = latest upstream tag (or --tag <tag>)
 *   ours   = the files in this repository
 *
 * Files you never changed are updated, files you customised are merged, and
 * overlapping edits are left with conflict markers (<<<<<<<) to resolve.
 *
 * Usage: node scripts/update-woonuxt.mjs [--tag 4.30.2] [--dry-run] [--no-install]
 */
import { execFileSync } from 'node:child_process';
import { existsSync, mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const REPO_URL = process.env.WOONUXT_REPO_URL || 'https://github.com/scottyzen/woonuxt.git';
const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const BASE_PKG = 'woonuxt_base/package.json';

// Paths synced from upstream. Lockfile is regenerated by npm install instead.
const SYNC_DIRS = ['woonuxt_base/'];
const SYNC_FILES = [
  'package.json',
  'nuxt.config.ts',
  'codegen.ts',
  'eslint.config.mjs',
  'tsconfig.json',
  'netlify.toml',
  'vercel.json',
  'CONTRIBUTING.md',
  'scripts/update-woonuxt.mjs',
];
// Generated or storefront-specific content that must never be overwritten.
const IGNORE = [/^woonuxt_base\/app\/gql\/(default|schema)\.ts$/, /^woonuxt_base\/public\//];

const args = process.argv.slice(2);
const dryRun = args.includes('--dry-run');
const skipInstall = args.includes('--no-install');
const tagArg = args.includes('--tag') ? args[args.indexOf('--tag') + 1] : null;

const run = (cmd, cmdArgs, opts = {}) => execFileSync(cmd, cmdArgs, { encoding: 'utf8', stdio: ['ignore', 'pipe', 'inherit'], ...opts });
const parse = (v) =>
  v
    .replace(/^v/, '')
    .split('.')
    .map((n) => parseInt(n, 10) || 0);
const compare = (a, b) => {
  const [x, y] = [parse(a), parse(b)];
  for (let i = 0; i < 3; i++) if ((x[i] || 0) !== (y[i] || 0)) return (x[i] || 0) - (y[i] || 0);
  return 0;
};

const currentVersion = JSON.parse(readFileSync(join(ROOT, BASE_PKG), 'utf8')).version;

const tags = run('git', ['ls-remote', '--tags', '--refs', REPO_URL])
  .split('\n')
  .map((l) => l.split('refs/tags/')[1])
  .filter((t) => t && /^v?\d+\.\d+\.\d+$/.test(t));
const findTag = (version) => tags.find((t) => t.replace(/^v/, '') === version.replace(/^v/, ''));

const latestTag = tagArg || [...tags].sort(compare).pop();
if (!latestTag || !tags.includes(latestTag)) throw new Error(`Upstream tag not found: ${latestTag}`);
const baseTag = findTag(currentVersion);

console.log(`Current: ${currentVersion}  Target: ${latestTag}`);
if (compare(currentVersion, latestTag) === 0) {
  console.log('Already up to date.');
  process.exit(0);
}
if (!baseTag) console.warn(`No upstream tag for ${currentVersion}; treating every differing file as a potential conflict.`);

const tmp = mkdtempSync(join(tmpdir(), 'woonuxt-'));
try {
  run('git', ['clone', '--quiet', '--no-checkout', REPO_URL, tmp]);
  const git = (...a) => run('git', ['-C', tmp, ...a]);
  const gitBuf = (...a) => execFileSync('git', ['-C', tmp, ...a], { maxBuffer: 1 << 28 });
  const list = (tag) => (tag ? git('ls-tree', '-r', '--name-only', tag).split('\n').filter(Boolean) : []);
  const wanted = (p) => !IGNORE.some((r) => r.test(p)) && (SYNC_FILES.includes(p) || SYNC_DIRS.some((d) => p.startsWith(d)));

  const baseFiles = new Set(list(baseTag));
  const newFiles = new Set(list(latestTag));
  const paths = [...new Set([...baseFiles, ...newFiles])].filter(wanted).sort();

  const result = { added: [], updated: [], merged: [], conflicts: [], deleted: [], kept: [] };
  const write = (p, data) => {
    if (dryRun) return;
    mkdirSync(dirname(join(ROOT, p)), { recursive: true });
    writeFileSync(join(ROOT, p), data);
  };

  for (const p of paths) {
    const base = baseFiles.has(p) ? gitBuf('show', `${baseTag}:${p}`) : null;
    const theirs = newFiles.has(p) ? gitBuf('show', `${latestTag}:${p}`) : null;
    const local = existsSync(join(ROOT, p)) ? readFileSync(join(ROOT, p)) : null;

    if (base && theirs && base.equals(theirs)) continue;

    if (!theirs) {
      // Removed upstream: delete only if the local copy is untouched.
      if (!local) continue;
      if (base && local.equals(base)) {
        if (!dryRun) rmSync(join(ROOT, p));
        result.deleted.push(p);
      } else result.kept.push(p);
      continue;
    }
    if (!local) {
      // Locally deleted files stay deleted when they existed in the base.
      if (base) result.kept.push(p);
      else {
        write(p, theirs);
        result.added.push(p);
      }
      continue;
    }
    if (local.equals(theirs)) continue;
    if (base && local.equals(base)) {
      write(p, theirs);
      result.updated.push(p);
      continue;
    }

    // Both sides changed: 3-way merge with git.
    const dir = mkdtempSync(join(tmp, 'm-'));
    const files = { ours: join(dir, 'ours'), base: join(dir, 'base'), theirs: join(dir, 'theirs') };
    writeFileSync(files.ours, local);
    writeFileSync(files.base, base ?? '');
    writeFileSync(files.theirs, theirs);
    let conflicted = false;
    let merged;
    try {
      merged = execFileSync(
        'git',
        ['merge-file', '-p', '-L', 'local', '-L', `base ${baseTag ?? 'none'}`, '-L', `upstream ${latestTag}`, files.ours, files.base, files.theirs],
        { maxBuffer: 1 << 28 },
      );
    } catch (e) {
      if (e.status > 0 && e.stdout) {
        conflicted = true;
        merged = e.stdout;
      } else throw e;
    }
    write(p, merged);
    (conflicted ? result.conflicts : result.merged).push(p);
  }

  const section = (title, items) => items.length && console.log(`\n${title} (${items.length})\n${items.map((i) => `  ${i}`).join('\n')}`);
  console.log(dryRun ? '\n[dry run] no files were written' : '');
  section('Added', result.added);
  section('Updated', result.updated);
  section('Merged with local changes', result.merged);
  section('CONFLICTS - resolve the <<<<<<< markers', result.conflicts);
  section('Deleted upstream', result.deleted);
  section('Kept (locally deleted, or removed upstream but customised)', result.kept);

  if (dryRun) process.exit(0);

  if (result.conflicts.length) {
    console.log(
      '\nResolve the conflicts by hand, then run `npm install` and commit.\nRe-running this script will not redo the merge: the version is already updated.',
    );
    process.exit(1);
  }
  if (!skipInstall) {
    console.log('\nRunning npm install to refresh package-lock.json...');
    execFileSync('npm', ['install', '--no-audit', '--no-fund'], { cwd: ROOT, stdio: 'inherit' });
  }
  console.log(`\nUpdated to ${latestTag}. Review with \`git diff\`, then commit and push to deploy.`);
} finally {
  rmSync(tmp, { recursive: true, force: true });
}
